#!/usr/bin/env node
/**
 * Generate idempotent PostgreSQL to seed topics, subtopics, and activities
 * from data/topics.csv and data/miniquiz-activities.csv.
 *
 * Uses UUID v5 so topic/subtopic IDs are stable across runs (same as former Python script).
 *
 * Usage (from repo root):
 *   node scripts/generate-activities-seed-sql.js -o db/seeds/activities.sql
 *   node scripts/generate-activities-seed-sql.js
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { parse } = require('csv-parse/sync');
const { v5: uuidv5 } = require('uuid');

const REPO_ROOT = path.resolve(__dirname, '..');
const DEFAULT_TOPICS = path.join(REPO_ROOT, 'data', 'topics.csv');
const DEFAULT_ACTIVITIES = path.join(REPO_ROOT, 'data', 'miniquiz-activities.csv');

const SEED_NAMESPACE = uuidv5('https://archimedes-infrastructure/db-seed-v1', uuidv5.URL);

function topicUuid(topic) {
  return uuidv5(`topic:${topic}`, SEED_NAMESPACE);
}

function subtopicUuid(topic, subtopic) {
  return uuidv5(`subtopic:${topic}\x1e${subtopic}`, SEED_NAMESPACE);
}

function sqlStr(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function parseCsvFile(filePath) {
  const buf = fs.readFileSync(filePath);
  let text = buf.toString('utf8');
  if (text.charCodeAt(0) === 0xfeff) {
    text = text.slice(1);
  }
  return parse(text, {
    columns: true,
    skip_empty_lines: true,
    trim: true,
    relax_column_count: true,
  });
}

function loadTopicSubtopicPairs(filePath) {
  const rows = parseCsvFile(filePath);
  const pairs = [];
  for (const row of rows) {
    const t = (row.TOPIC || '').trim();
    const s = (row.SUBTOPIC || '').trim();
    if (!t || !s) continue;
    pairs.push([t, s]);
  }
  return pairs;
}

function loadActivities(filePath) {
  const rows = parseCsvFile(filePath);
  const out = [];
  for (const row of rows) {
    const t = (row.TOPIC || '').trim();
    const s = (row.SUBTOPIC || '').trim();
    const aid = (row.ACTIVITY_ID || '').trim();
    const desc = (row.ACTIVITY_DESCRIPTION || '').trim();
    if (!t || !s || !aid) continue;
    out.push([t, s, aid, desc]);
  }
  return out;
}

/**
 * @returns {{ topicOrder: Map<string, number>, subtopicOrder: Map<string, { topic: string, sub: string, ord: number }> }}
 */
function buildTaxonomy(pairsTopicsCsv, activityRows) {
  const topicOrder = new Map();
  const subtopicOrder = new Map();

  function bumpTopic(name) {
    if (!topicOrder.has(name)) {
      topicOrder.set(name, topicOrder.size + 1);
    }
  }

  function subtopicKey(topic, sub) {
    return `${topic}\x1e${sub}`;
  }

  function bumpSubtopic(topic, sub) {
    const key = subtopicKey(topic, sub);
    if (subtopicOrder.has(key)) return;
    let count = 0;
    for (const k of subtopicOrder.keys()) {
      const [tp] = k.split('\x1e');
      if (tp === topic) count += 1;
    }
    subtopicOrder.set(key, { topic, sub, ord: count + 1 });
  }

  for (const [t, s] of pairsTopicsCsv) {
    bumpTopic(t);
    bumpSubtopic(t, s);
  }
  for (const [t, s] of activityRows) {
    bumpTopic(t);
    bumpSubtopic(t, s);
  }

  return { topicOrder, subtopicOrder };
}

function parseArgs(argv) {
  const opts = {
    topics: DEFAULT_TOPICS,
    activities: DEFAULT_ACTIVITIES,
    output: null,
  };
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a === '-o' || a === '--output') {
      opts.output = argv[++i];
    } else if (a === '--topics') {
      opts.topics = argv[++i];
    } else if (a === '--activities') {
      opts.activities = argv[++i];
    } else if (a === '-h' || a === '--help') {
      opts.help = true;
    }
  }
  return opts;
}

function main() {
  const opts = parseArgs(process.argv);
  if (opts.help) {
    console.error(`Usage: node scripts/generate-activities-seed-sql.js [-o OUT] [--topics PATH] [--activities PATH]`);
    process.exit(0);
  }

  if (!fs.existsSync(opts.topics) || !fs.statSync(opts.topics).isFile()) {
    console.error(`error: topics file not found: ${opts.topics}`);
    process.exit(1);
  }
  if (!fs.existsSync(opts.activities) || !fs.statSync(opts.activities).isFile()) {
    console.error(`error: activities file not found: ${opts.activities}`);
    process.exit(1);
  }

  const pairs = loadTopicSubtopicPairs(opts.topics);
  const activityRows = loadActivities(opts.activities);
  const { topicOrder, subtopicOrder } = buildTaxonomy(pairs, activityRows);

  const lines = [
    '-- Generated by scripts/generate-activities-seed-sql.js — do not edit by hand.',
    '-- Idempotent upserts: safe to re-run.',
    '',
    'BEGIN;',
    '',
  ];

  for (const [name, ord] of topicOrder) {
    const tid = topicUuid(name);
    lines.push(
      `INSERT INTO topics (id, name, display_order) VALUES (${sqlStr(tid)}, ${sqlStr(name)}, ${ord}) ` +
        `ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, display_order = EXCLUDED.display_order;`
    );
  }

  lines.push('');

  for (const { topic: topicName, sub: subName, ord } of subtopicOrder.values()) {
    const sid = subtopicUuid(topicName, subName);
    const tid = topicUuid(topicName);
    lines.push(
      `INSERT INTO subtopics (id, topic_id, name, display_order) VALUES ` +
        `(${sqlStr(sid)}, ${sqlStr(tid)}, ${sqlStr(subName)}, ${ord}) ` +
        `ON CONFLICT (id) DO UPDATE SET ` +
        `topic_id = EXCLUDED.topic_id, name = EXCLUDED.name, display_order = EXCLUDED.display_order;`
    );
  }

  lines.push('');

  const activityIdFirstSubtopic = new Map();
  let skipped = 0;
  for (const [t, s, aid, desc0] of activityRows) {
    if (aid.length > 20) {
      console.warn(`warning: ACTIVITY_ID longer than 20 chars, may fail DB constraint: ${JSON.stringify(aid)}`);
    }
    if (activityIdFirstSubtopic.has(aid)) {
      const prev = activityIdFirstSubtopic.get(aid);
      if (prev[0] !== t || prev[1] !== s) {
        console.warn(
          `warning: skipping duplicate ACTIVITY_ID ${JSON.stringify(aid)} for (${JSON.stringify(t)}, ${JSON.stringify(s)}); ` +
            `keeping (${JSON.stringify(prev[0])}, ${JSON.stringify(prev[1])})`
        );
        skipped += 1;
      }
      continue;
    }
    activityIdFirstSubtopic.set(aid, [t, s]);

    let desc = desc0;
    if (desc.length > 500) {
      console.warn(`warning: description truncated to 500 chars for ${JSON.stringify(aid)}`);
      desc = desc.slice(0, 500);
    }

    const sid = subtopicUuid(t, s);
    // created_at: set on insert (NOT NULL-safe if DB has no column default). On conflict, leave timestamp unchanged.
    lines.push(
      `INSERT INTO activities (activity_id, subtopic_id, description, activity_type, created_at) VALUES ` +
        `(${sqlStr(aid)}, ${sqlStr(sid)}, ${sqlStr(desc)}, 'miniquiz', NOW()) ` +
        `ON CONFLICT (activity_id) DO UPDATE SET ` +
        `subtopic_id = EXCLUDED.subtopic_id, description = EXCLUDED.description, ` +
        `activity_type = EXCLUDED.activity_type;`
    );
  }

  lines.push('', 'COMMIT;', '');

  const out = lines.join('\n');
  if (opts.output) {
    fs.mkdirSync(path.dirname(opts.output), { recursive: true });
    fs.writeFileSync(opts.output, out, 'utf8');
    console.error(
      `wrote ${opts.output} (${activityRows.length - skipped} activity upserts, ${skipped} skipped)`
    );
  } else {
    process.stdout.write(out);
  }
}

main();
