#!/usr/bin/env node
/**
 * Generate idempotent PostgreSQL to seed `schools` from PEIMS-style CSV
 * (default: data/schools_2023_to_2024.csv).
 *
 * Maps columns to db/archimedes-schema.sql `schools` table. Stable UUID v5
 * per `USER_School_Number` for `id`. Upserts on `code` (UNIQUE).
 *
 * Usage (from repo root):
 *   node scripts/generate-schools-seed-sql.js -o db/seeds/schools.sql
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { parse } = require('csv-parse/sync');
const { v5: uuidv5 } = require('uuid');

const REPO_ROOT = path.resolve(__dirname, '..');
const DEFAULT_CSV = path.join(REPO_ROOT, 'data', 'schools_2023_to_2024.csv');

const SCHOOL_SEED_NS = uuidv5('https://archimedes-infrastructure/schools-seed-v1', uuidv5.URL);

function sqlStr(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** SQL literal or NULL for empty optional string. */
function sqlOpt(value, maxLen) {
  const t = clip(trim(value), maxLen);
  return t ? sqlStr(t) : 'NULL';
}

function trim(v) {
  return v == null ? '' : String(v).trim();
}

function clip(s, max) {
  if (s.length <= max) return s;
  return s.slice(0, max);
}

function parseCsvFile(filePath) {
  const buf = fs.readFileSync(filePath);
  let text = buf.toString('utf8');
  if (text.charCodeAt(0) === 0xfeff) {
    text = text.slice(1);
  }
  return parse(text, {
    columns: true,
    skip_empty_lines: true,
    trim: true,
    relax_column_count: true,
  });
}

function schoolIdForCode(code) {
  return uuidv5(`school:${code}`, SCHOOL_SEED_NS);
}

function rowToSchool(row) {
  const code = trim(row.USER_School_Number);
  const name = clip(trim(row.USER_School_Name), 200);
  const siteAddr = trim(row.USER_School_Site_Street_Address);
  const mailAddr = trim(row.USER_School_Street_Address);
  const address = clip(siteAddr || mailAddr, 500);

  const siteCity = trim(row.USER_School_Site_City);
  const mailCity = trim(row.USER_School_City);
  const city = clip(siteCity || mailCity, 100);

  const siteState = trim(row.USER_School_Site_State);
  const mailState = trim(row.USER_School_State);
  const state = clip(siteState || mailState, 50);

  const siteZip = trim(row.USER_School_Site_Zip);
  const mailZip = trim(row.USER_School_Zip);
  const zip = clip(siteZip || mailZip, 20);

  const phone = clip(trim(row.USER_School_Phone), 20);
  const email = clip(trim(row.USER_School_Email_Address), 255);
  const website = clip(trim(row.USER_School_Web_Page_Address), 200);

  const status = trim(row.USER_School_Status);
  const isActive = /^active$/i.test(status);

  return { code, name, address, city, state, zip, phone, email, website, isActive };
}

function parseArgs(argv) {
  const opts = { input: DEFAULT_CSV, output: null };
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a === '-o' || a === '--output') {
      opts.output = argv[++i];
    } else if (a === '-i' || a === '--input') {
      opts.input = argv[++i];
    } else if (a === '-h' || a === '--help') {
      opts.help = true;
    }
  }
  return opts;
}

function main() {
  const opts = parseArgs(process.argv);
  if (opts.help) {
    console.error(
      'Usage: node scripts/generate-schools-seed-sql.js [-i schools.csv] [-o db/seeds/schools.sql]'
    );
    process.exit(0);
  }

  if (!fs.existsSync(opts.input) || !fs.statSync(opts.input).isFile()) {
    console.error(`error: input file not found: ${opts.input}`);
    process.exit(1);
  }

  const rows = parseCsvFile(opts.input);
  const lines = [
    '-- Generated by scripts/generate-schools-seed-sql.js — do not edit by hand.',
    '-- Idempotent upserts on schools.code (matches db/archimedes-schema.sql).',
    '',
    'BEGIN;',
    '',
  ];

  let written = 0;
  let skipped = 0;

  for (const row of rows) {
    const s = rowToSchool(row);
    if (!s.code) {
      skipped += 1;
      continue;
    }
    if (s.code.length > 10) {
      console.warn(`warning: skipping code longer than 10: ${JSON.stringify(s.code)}`);
      skipped += 1;
      continue;
    }
    if (!s.name) {
      console.warn(`warning: skipping row with empty name, code ${JSON.stringify(s.code)}`);
      skipped += 1;
      continue;
    }

    const id = schoolIdForCode(s.code);
    const addrSql = s.address ? sqlStr(s.address) : 'NULL';
    const citySql = sqlOpt(s.city, 100);
    const stateSql = sqlOpt(s.state, 50);
    const zipSql = sqlOpt(s.zip, 20);
    const phoneSql = s.phone ? sqlStr(s.phone) : 'NULL';
    const emailSql = sqlOpt(s.email, 255);
    const websiteSql = sqlOpt(s.website, 200);
    const activeSql = s.isActive ? 'TRUE' : 'FALSE';

    lines.push(
      `INSERT INTO schools (id, code, name, address, city, state, zip_code, phone, email, website, is_active) VALUES ` +
        `(${sqlStr(id)}, ${sqlStr(s.code)}, ${sqlStr(s.name)}, ${addrSql}, ${citySql}, ${stateSql}, ${zipSql}, ` +
        `${phoneSql}, ${emailSql}, ${websiteSql}, ${activeSql}) ` +
        `ON CONFLICT (code) DO UPDATE SET ` +
        `name = EXCLUDED.name, address = EXCLUDED.address, city = EXCLUDED.city, state = EXCLUDED.state, ` +
        `zip_code = EXCLUDED.zip_code, phone = EXCLUDED.phone, email = EXCLUDED.email, website = EXCLUDED.website, ` +
        `is_active = EXCLUDED.is_active;`
    );
    written += 1;
  }

  lines.push('', 'COMMIT;', '');

  const out = lines.join('\n');
  if (!opts.output) {
    process.stdout.write(out);
    console.error(`stderr: ${written} school upserts, ${skipped} skipped`);
    return;
  }

  fs.mkdirSync(path.dirname(opts.output), { recursive: true });
  fs.writeFileSync(opts.output, out, 'utf8');
  console.error(`wrote ${opts.output} (${written} school upserts, ${skipped} skipped)`);
}

main();
