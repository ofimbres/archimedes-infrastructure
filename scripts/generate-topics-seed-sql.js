#!/usr/bin/env node
/**
 * Generate idempotent SQL for `topics` and `subtopics` from data/topics.csv only.
 * Matches the ORM flow (unique topic names in CSV order, then unique (topic, subtopic) pairs).
 *
 * Uses the same UUID v5 namespace and formulas as generate-activities-seed-sql.js so any
 * topic/subtopic row that exists in topics.csv gets the same `id` as in activities.sql.
 *
 * Schema: db/archimedes-schema.sql (name VARCHAR(200), display_order INTEGER).
 *
 * Usage:
 *   node scripts/generate-topics-seed-sql.js -o db/seeds/topics.sql
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { parse } = require('csv-parse/sync');
const { v5: uuidv5 } = require('uuid');

const REPO_ROOT = path.resolve(__dirname, '..');
const DEFAULT_TOPICS = path.join(REPO_ROOT, 'data', 'topics.csv');

/** Must match generate-activities-seed-sql.js */
const SEED_NAMESPACE = uuidv5('https://archimedes-infrastructure/db-seed-v1', uuidv5.URL);

function topicUuid(topic) {
  return uuidv5(`topic:${topic}`, SEED_NAMESPACE);
}

function subtopicUuid(topic, subtopic) {
  return uuidv5(`subtopic:${topic}\x1e${subtopic}`, SEED_NAMESPACE);
}

function sqlStr(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function parseCsvFile(filePath) {
  const buf = fs.readFileSync(filePath);
  let text = buf.toString('utf8');
  if (text.charCodeAt(0) === 0xfeff) {
    text = text.slice(1);
  }
  return parse(text, {
    columns: true,
    skip_empty_lines: true,
    trim: true,
    relax_column_count: true,
  });
}

function loadTopicSubtopicPairs(filePath) {
  const rows = parseCsvFile(filePath);
  const pairs = [];
  for (const row of rows) {
    const t = (row.TOPIC || '').trim();
    const s = (row.SUBTOPIC || '').trim();
    if (!t || !s) continue;
    pairs.push([t, s]);
  }
  return pairs;
}

/**
 * Topics: first-seen order. Subtopics: first-seen (topic, sub) order, display_order per topic.
 * Same logic as buildTaxonomy(pairs, []) in generate-activities-seed-sql.js.
 */
function buildTaxonomyFromTopicsCsv(pairs) {
  const topicOrder = new Map();
  const subtopicOrder = new Map();

  function subtopicKey(topic, sub) {
    return `${topic}\x1e${sub}`;
  }

  function bumpTopic(name) {
    if (!topicOrder.has(name)) {
      topicOrder.set(name, topicOrder.size + 1);
    }
  }

  function bumpSubtopic(topic, sub) {
    const key = subtopicKey(topic, sub);
    if (subtopicOrder.has(key)) return;
    let count = 0;
    for (const k of subtopicOrder.keys()) {
      const [tp] = k.split('\x1e');
      if (tp === topic) count += 1;
    }
    subtopicOrder.set(key, { topic, sub, ord: count + 1 });
  }

  for (const [t, s] of pairs) {
    bumpTopic(t);
    bumpSubtopic(t, s);
  }

  return { topicOrder, subtopicOrder };
}

function parseArgs(argv) {
  const opts = { input: DEFAULT_TOPICS, output: null };
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a === '-o' || a === '--output') opts.output = argv[++i];
    else if (a === '-i' || a === '--input') opts.input = argv[++i];
    else if (a === '-h' || a === '--help') opts.help = true;
  }
  return opts;
}

function main() {
  const opts = parseArgs(process.argv);
  if (opts.help) {
    console.error('Usage: node scripts/generate-topics-seed-sql.js [-i topics.csv] [-o db/seeds/topics.sql]');
    process.exit(0);
  }

  if (!fs.existsSync(opts.input) || !fs.statSync(opts.input).isFile()) {
    console.error(`error: input file not found: ${opts.input}`);
    process.exit(1);
  }

  const pairs = loadTopicSubtopicPairs(opts.input);
  const { topicOrder, subtopicOrder } = buildTaxonomyFromTopicsCsv(pairs);

  const lines = [
    '-- Generated by scripts/generate-topics-seed-sql.js — do not edit by hand.',
    '-- Topics + subtopics from topics.csv only (same UUID v5 as activities seed).',
    '',
    'BEGIN;',
    '',
  ];

  for (const [name, ord] of topicOrder) {
    if (name.length > 200) {
      console.warn(`warning: topic name length ${name.length} > 200 (DB VARCHAR(200)): ${JSON.stringify(name.slice(0, 50))}...`);
    }
    const tid = topicUuid(name);
    lines.push(
      `INSERT INTO topics (id, name, display_order) VALUES (${sqlStr(tid)}, ${sqlStr(name)}, ${ord}) ` +
        `ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, display_order = EXCLUDED.display_order;`
    );
  }

  lines.push('');

  for (const { topic: topicName, sub: subName, ord } of subtopicOrder.values()) {
    if (subName.length > 200) {
      console.warn(`warning: subtopic name length ${subName.length} > 200: ${JSON.stringify(subName.slice(0, 50))}...`);
    }
    const sid = subtopicUuid(topicName, subName);
    const tid = topicUuid(topicName);
    lines.push(
      `INSERT INTO subtopics (id, topic_id, name, display_order) VALUES ` +
        `(${sqlStr(sid)}, ${sqlStr(tid)}, ${sqlStr(subName)}, ${ord}) ` +
        `ON CONFLICT (id) DO UPDATE SET ` +
        `topic_id = EXCLUDED.topic_id, name = EXCLUDED.name, display_order = EXCLUDED.display_order;`
    );
  }

  lines.push('', 'COMMIT;', '');

  const out = lines.join('\n');
  const nTopics = topicOrder.size;
  const nSubtopics = subtopicOrder.size;

  if (!opts.output) {
    process.stdout.write(out);
    console.error(`stderr: ${nTopics} topics, ${nSubtopics} subtopics`);
    return;
  }

  fs.mkdirSync(path.dirname(opts.output), { recursive: true });
  fs.writeFileSync(opts.output, out, 'utf8');
  console.error(`wrote ${opts.output} (${nTopics} topics, ${nSubtopics} subtopics)`);
}

main();
